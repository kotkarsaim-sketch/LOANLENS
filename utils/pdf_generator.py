"""
utils/pdf_generator.py - Professional PDF Report Generator for LoanLens
Uses fpdf2 to export an executive loan comparison summary report.
"""

from fpdf import FPDF
from fpdf.enums import XPos, YPos
from typing import List, Dict, Any
from utils.formatting import format_inr, format_percent, format_tenure_display
import datetime


class LoanLensPDF(FPDF):
    def header(self):
        # Deep Navy header bar
        self.set_fill_color(15, 39, 68)  # #0F2744
        self.rect(0, 0, 210, 28, 'F')
        
        self.set_font('Helvetica', 'B', 18)
        self.set_text_color(255, 255, 255)
        self.set_xy(14, 7)
        self.cell(0, 8, 'LoanLens - Executive Loan Comparison Report', new_x=XPos.LMARGIN, new_y=YPos.NEXT, align='L')
        
        self.set_font('Helvetica', '', 9)
        self.set_text_color(20, 184, 166)  # Teal accent
        self.set_xy(14, 16)
        self.cell(0, 6, 'Smart Financial Intelligence & Cost-of-Credit Analysis', new_x=XPos.LMARGIN, new_y=YPos.NEXT, align='L')
        self.ln(12)

    def footer(self):
        self.set_y(-18)
        self.set_font('Helvetica', 'I', 8)
        self.set_text_color(148, 163, 184)
        date_str = datetime.datetime.now().strftime("%d %b %Y, %I:%M %p")
        self.cell(0, 8, f'Generated by LoanLens (Fintech Academic Edition) on {date_str}  |  Page {self.page_no()}', new_x=XPos.RIGHT, new_y=YPos.TOP, align='C')


def generate_comparison_pdf(summaries: List[Dict[str, Any]], winner_summary: Dict[str, Any], runner_up: Dict[str, Any] = None) -> bytes:
    """
    Generate a styled executive summary PDF report of the compared loans.
    """
    pdf = LoanLensPDF(orientation='P', unit='mm', format='A4')
    pdf.set_auto_page_break(auto=True, margin=20)
    pdf.add_page()
    
    # 1. Executive Summary / Recommendation Box
    pdf.set_y(34)
    pdf.set_fill_color(240, 253, 250)  # Very soft teal tint
    pdf.set_draw_color(13, 148, 136)   # Teal border
    pdf.set_line_width(0.5)
    pdf.rect(14, 34, 182, 38, 'FD')
    
    pdf.set_xy(18, 38)
    pdf.set_font('Helvetica', 'B', 12)
    pdf.set_text_color(15, 39, 68)
    pdf.cell(0, 6, f"RECOMMENDED OPTION: {winner_summary['name'].upper()}", new_x=XPos.LMARGIN, new_y=YPos.NEXT, align='L')
    
    pdf.set_xy(18, 46)
    pdf.set_font('Helvetica', '', 9.5)
    pdf.set_text_color(71, 85, 105)
    
    savings_text = ""
    if runner_up and runner_up['total_cost_of_credit'] > winner_summary['total_cost_of_credit']:
        diff = runner_up['total_cost_of_credit'] - winner_summary['total_cost_of_credit']
        savings_text = f" This saves an estimated Rs. {diff:,.0f} compared to {runner_up['name']}."
    
    pdf.multi_cell(174, 5, 
        f"Based on comprehensive cost-of-credit modeling, {winner_summary['name']} offers the lowest total lifetime borrowing cost of Rs. {winner_summary['total_cost_of_credit']:,.0f} with an effective APR of {winner_summary['effective_apr']:.2f}%.{savings_text}")
    
    pdf.set_xy(18, 62)
    pdf.set_font('Helvetica', 'B', 9)
    pdf.set_text_color(13, 148, 136)
    pdf.cell(0, 6, f"Monthly EMI: Rs. {winner_summary['emi']:,.0f}   |   Effective APR: {winner_summary['effective_apr']:.2f}%   |   Upfront Fees: Rs. {winner_summary['total_upfront_fees']:,.0f}", new_x=XPos.LMARGIN, new_y=YPos.NEXT, align='L')
    
    # 2. Section: Side-by-Side Evaluation Matrix
    pdf.set_y(78)
    pdf.set_font('Helvetica', 'B', 12)
    pdf.set_text_color(15, 39, 68)
    pdf.cell(0, 8, "Side-by-Side Financial Evaluation Matrix", new_x=XPos.LMARGIN, new_y=YPos.NEXT, align='L')
    pdf.ln(2)
    
    # Table Headers
    col_w_metric = 62
    num_loans = len(summaries)
    col_w_val = (182 - col_w_metric) / num_loans
    
    pdf.set_fill_color(15, 39, 68)
    pdf.set_text_color(255, 255, 255)
    pdf.set_font('Helvetica', 'B', 8.5)
    
    pdf.cell(col_w_metric, 8, " Financial Metric", border=1, new_x=XPos.RIGHT, new_y=YPos.TOP, align='L', fill=True)
    for s in summaries:
        name_short = s['name'][:18] + (".." if len(s['name']) > 18 else "")
        pdf.cell(col_w_val, 8, f" {name_short}", border=1, new_x=XPos.RIGHT, new_y=YPos.TOP, align='C', fill=True)
    pdf.ln()
    
    # Table Rows
    def fmt_rs(val):
        return f"Rs. {val:,.0f}"

    metrics_list = [
        ("Loan Principal", lambda s: fmt_rs(s['principal'])),
        ("Interest Rate (p.a.)", lambda s: f"{s['annual_rate_pct']:.2f}%"),
        ("Tenure", lambda s: format_tenure_display(s['tenure_months'])),
        ("Monthly EMI", lambda s: fmt_rs(s['emi'])),
        ("Total Interest Payable", lambda s: fmt_rs(s['total_interest'])),
        ("Processing Fee", lambda s: fmt_rs(s['processing_fee_base'])),
        ("GST on Fees (18%)", lambda s: fmt_rs(s['fee_gst'])),
        ("Other Charges (Doc/Ins)", lambda s: fmt_rs(s['documentation_charges'] + s['insurance_charges'])),
        ("Total Upfront Deductions", lambda s: fmt_rs(s['total_upfront_fees'])),
        ("Net Cash Disbursed", lambda s: fmt_rs(s['net_disbursed'])),
        ("Total Cost of Credit", lambda s: fmt_rs(s['total_cost_of_credit'])),
        ("Total Outflow", lambda s: fmt_rs(s['total_outflow'])),
        ("Effective APR", lambda s: f"{s['effective_apr']:.2f}%"),
    ]
    
    pdf.set_font('Helvetica', '', 8)
    fill = False
    for label, fn in metrics_list:
        pdf.set_fill_color(248, 250, 252) if fill else pdf.set_fill_color(255, 255, 255)
        pdf.set_draw_color(226, 232, 240)
        pdf.set_text_color(30, 41, 59)
        
        is_highlight = label in ["Monthly EMI", "Total Cost of Credit", "Effective APR"]
        if is_highlight:
            pdf.set_font('Helvetica', 'B', 8)
            pdf.set_text_color(15, 39, 68)
        else:
            pdf.set_font('Helvetica', '', 8)
            pdf.set_text_color(71, 85, 105)
            
        pdf.cell(col_w_metric, 6.5, f" {label}", border=1, new_x=XPos.RIGHT, new_y=YPos.TOP, align='L', fill=fill)
        
        for s in summaries:
            val_text = fn(s)
            pdf.cell(col_w_val, 6.5, f" {val_text}", border=1, new_x=XPos.RIGHT, new_y=YPos.TOP, align='C', fill=fill)
        pdf.ln()
        fill = not fill
        
    # 3. Methodology & Consumer Guidance
    pdf.ln(6)
    pdf.set_font('Helvetica', 'B', 10)
    pdf.set_text_color(15, 39, 68)
    pdf.cell(0, 6, "Important Consumer Fintech Disclosures", new_x=XPos.LMARGIN, new_y=YPos.NEXT, align='L')
    
    pdf.set_font('Helvetica', '', 8)
    pdf.set_text_color(100, 116, 139)
    notes = [
        "1. Effective APR is computed via internal rate of return (IRR) root-finding using net disbursed capital.",
        "2. GST is charged at statutory 18% on all processing, administrative, and inspection fees under Indian tax laws.",
        "3. Standard reducing balance formula: EMI = [P * r * (1+r)^n] / [(1+r)^n - 1].",
        "4. Prepayment flexibilities and floating-rate benchmark resets may alter actual maturity cashflows."
    ]
    for n in notes:
        pdf.cell(0, 4.5, n, new_x=XPos.LMARGIN, new_y=YPos.NEXT, align='L')
        
    return bytes(pdf.output())
